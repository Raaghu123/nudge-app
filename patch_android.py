"""CI helper: inject permissions + core desugaring into fresh flutter-create output.

Desugaring is APPENDED as extra blocks (Gradle merges duplicate blocks),
so it works regardless of template formatting — no fragile regex.
"""
import pathlib
import re

m = pathlib.Path('android/app/src/main/AndroidManifest.xml')
if not m.exists():
    print('manifest missing, skipping (run flutter create first)')
    raise SystemExit(0)
t = m.read_text()

# ---- Phase 1: Permissions for flutter_local_notifications v17+ ----
perms = (
    '    <uses-permission android:name="android.permission.POST_NOTIFICATIONS"/>\n'
    '    <uses-permission android:name="android.permission.SCHEDULE_EXACT_ALARM"/>\n'
    # NOTE: USE_EXACT_ALARM intentionally omitted. On Android 14+ it is
    # restricted to clock/calendar apps; declaring it on this reminder app
    # gets it silently rejected on Android 16 (OnePlus/OxygenOS confirmed),
    # which downgrades exact alarms to inexact AND hides the app from the
    # Alarms & reminders settings list. SCHEDULE_EXACT_ALARM alone keeps the
    # toggle visible so the user can grant it; initialize() requests it via
    # requestExactAlarmsPermission().
    '    <uses-permission android:name="android.permission.RECEIVE_BOOT_COMPLETED"/>\n'
    '    <uses-permission android:name="android.permission.VIBRATE"/>\n'
    '    <uses-permission android:name="android.permission.WAKE_LOCK"/>\n'
)
if 'POST_NOTIFICATIONS' not in t:
    t = t.replace('<application', perms + '<application', 1)
    m.write_text(t)
    print('permissions injected')
else:
    print('permissions already present')

# ---- Phase 1: flutter_local_notifications receivers inside <application> ----
# ActionBroadcastReceiver is REQUIRED for notification action buttons
# (Done/Snooze): without it the action PendingIntents have no target and
# taps silently do nothing. Matches the plugin README manifest setup.
receivers = (
    '    <receiver android:exported="false" android:name="com.dexterous.flutterlocalnotifications.ActionBroadcastReceiver" />\n'
    '    <receiver android:exported="false" android:name="com.dexterous.flutterlocalnotifications.ScheduledNotificationReceiver" />\n'
    '    <receiver android:exported="false" android:name="com.dexterous.flutterlocalnotifications.ScheduledNotificationBootReceiver">\n'
    '        <intent-filter>\n'
    '            <action android:name="android.intent.action.BOOT_COMPLETED" />\n'
    '            <action android:name="android.intent.action.MY_PACKAGE_REPLACED" />\n'
    '            <action android:name="android.intent.action.QUICKBOOT_POWERON" />\n'
    '            <action android:name="com.htc.intent.action.QUICKBOOT_POWERON" />\n'
    '        </intent-filter>\n'
    '    </receiver>\n'
)
if 'ActionBroadcastReceiver' not in t or 'ScheduledNotificationReceiver' not in t:
    t = t.replace('</application>', receivers + '</application>', 1)
    m.write_text(t)
    print('receivers injected')
else:
    print('receivers already present')

# ---- Phase 1: nudge/system platform channel in MainActivity ----
# Settings.Global.BOOT_COUNT (reboot detection) and Build.MANUFACTURER (OEM
# settings deep links) have no Dart API, so MainActivity exposes them over a
# MethodChannel, plus two launch helpers. android/ is regenerated by
# `flutter create` on every CI run, so the channel is injected here rather
# than hand-committed. The Dart side (lib/services/system_channel.dart)
# degrades gracefully if this patch ever fails to apply: features log and
# skip instead of crashing, and CI stays green.
kt_files = list(pathlib.Path('android/app/src/main').rglob('MainActivity.kt'))
if not kt_files:
    print('WARNING: MainActivity.kt not found, skipping system channel injection')
else:
    kt = kt_files[0]
    s = kt.read_text()
    if 'nudge/system' in s:
        print('system channel already present')
    else:
        needed_imports = [
            'import android.content.ActivityNotFoundException',
            'import android.content.Intent',
            'import android.net.Uri',
            'import android.os.Build',
            'import android.provider.Settings',
            'import io.flutter.embedding.engine.FlutterEngine',
            'import io.flutter.plugin.common.MethodChannel',
        ]
        missing = [i for i in needed_imports if i not in s]
        if missing:
            k_lines = s.split('\n')
            import_idx = [i for i, l in enumerate(k_lines) if l.startswith('import ')]
            if import_idx:
                k_lines[import_idx[-1] + 1:import_idx[-1] + 1] = missing
            else:
                pkg_idx = next((i for i, l in enumerate(k_lines) if l.startswith('package ')), 0)
                k_lines[pkg_idx + 1:pkg_idx + 1] = missing
            s = '\n'.join(k_lines)
        channel_body = '''class MainActivity : FlutterActivity() {
    override fun configureFlutterEngine(flutterEngine: FlutterEngine) {
        super.configureFlutterEngine(flutterEngine)
        MethodChannel(flutterEngine.dartExecutor.binaryMessenger, "nudge/system").setMethodCallHandler { call, result ->
            when (call.method) {
                "getBootCount" -> {
                    try {
                        val count = Settings.Global.getInt(contentResolver, Settings.Global.BOOT_COUNT, 0)
                        result.success(count)
                    } catch (e: Exception) {
                        result.error("BOOT_COUNT_ERROR", e.message, null)
                    }
                }
                "getManufacturer" -> result.success(Build.MANUFACTURER ?: "unknown")
                "openComponent" -> {
                    try {
                        val intent = Intent().setClassName(
                            call.argument<String>("package")!!,
                            call.argument<String>("class")!!
                        ).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
                        startActivity(intent)
                        result.success(true)
                    } catch (e: ActivityNotFoundException) {
                        result.success(false)
                    }
                }
                "openAppDetails" -> {
                    val intent = Intent(
                        Settings.ACTION_APPLICATION_DETAILS_SETTINGS,
                        Uri.parse("package:$packageName")
                    ).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
                    startActivity(intent)
                    result.success(true)
                }
                else -> result.notImplemented()
            }
        }
    }
}'''
        # Replace the class declaration only when the template body is empty
        # (bare declaration, or declaration plus an empty `{ }` block).
        # Anything else means the template changed: warn and skip rather than
        # emit uncompilable Kotlin.
        decl = re.search(r'(?m)^class\s+MainActivity[^\n]*$', s)
        tail_end = None
        if decl is not None:
            rest = s[decl.end():]
            if rest.strip() == '':
                tail_end = decl.end()
            else:
                m2 = re.match(r'[ \t]*\n[ \t]*\}[ \t]*\n?', rest)
                if m2 is not None and rest[m2.end():].strip() == '':
                    tail_end = decl.end() + m2.end()
        if tail_end is None:
            print('WARNING: MainActivity template not recognized, skipping system channel injection')
        else:
            kt.write_text(s[:decl.start()] + channel_body + s[tail_end:])
            print('system channel injected into MainActivity')

# Core desugaring for flutter_local_notifications v17+
groovy = pathlib.Path('android/app/build.gradle')
kts = pathlib.Path('android/app/build.gradle.kts')
if kts.exists():
    s = kts.read_text()
    if 'desugar_jdk_libs' not in s:
        with kts.open('a') as f:
            f.write(
                '\n// Nudge: core desugaring for flutter_local_notifications\n'
                'android {\n'
                '    compileOptions {\n'
                '        isCoreLibraryDesugaringEnabled = true\n'
                '    }\n'
                '}\n'
                'dependencies {\n'
                '    coreLibraryDesugaring("com.android.tools:desugar_jdk_libs:2.1.4")\n'
                '}\n'
            )
        print('desugaring appended to build.gradle.kts')
    else:
        print('kts already has desugaring')
elif groovy.exists():
    s = groovy.read_text()
    if 'desugar_jdk_libs' not in s:
        with groovy.open('a') as f:
            f.write(
                '\n// Nudge: core desugaring for flutter_local_notifications\n'
                'android {\n'
                '    compileOptions {\n'
                '        coreLibraryDesugaringEnabled true\n'
                '    }\n'
                '}\n'
                'dependencies {\n'
                "    coreLibraryDesugaring 'com.android.tools:desugar_jdk_libs:2.1.4'\n"
                '}\n'
            )
        print('desugaring appended to build.gradle')
    else:
        print('groovy already has desugaring')
else:
    print('WARNING: no app build file found')